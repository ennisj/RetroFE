    ThemeFolderKind classifyFirstLine(const std::string& firstLine)
    {
        if (firstLine.empty()) return TF_FRESH;
        return isEditorMarker(firstLine) ? TF_EDITOR : TF_FOREIGN;
    }

    namespace
    {
        // A collection name usable as a folder under collections/ as it is:
        // Windows would silently drop a trailing dot or space and write
        // somewhere else
        bool collectionFolderOk(const std::string& c) { return folderNameSafe(c); }

        // Does a generated page place firstLetter art? (Generated opening tags are one line each.)
        bool usesLetterArt(const std::string& xml)
        {
            size_t pos = 0;
            while ((pos = xml.find("<reloadableImage", pos)) != std::string::npos) {
                const size_t end = xml.find('>', pos);
                if (xml.substr(pos, end == std::string::npos ? std::string::npos : end - pos).find("type=\"firstLetter\"") != std::string::npos) {
                    return true;
                }
                pos += 16;
            }
            return false;
        }
    }

    SavePlan buildSavePlan(const ThemeProject& p, const WidgetLibrary& lib, const SaveInputs& inputs)
    {
        SavePlan plan;
        plan.files.push_back({ PROJECT_FILE, projectSerialize(p) });

        GenOptions opt;   // full pages: animations on, nothing filtered
        opt.themeDir = inputs.themeDir.empty() ? themeFolderName(p.name) : inputs.themeDir;
        bool wantsLetters = false;

        auto addPage = [&](const std::string& rel, const std::string& label, const std::string& xml) {
            plan.files.push_back({ rel, xml });
            if (inputs.checkLayouts) {
                for (const auto& issue : checkLayoutXml(xml)) plan.warnings.push_back(label + ": " + issue);
            }
        };

        for (const auto& page : p.pages) {
            const std::string label = page.collection.empty() ? std::string("Default") : page.displayName();
            std::string rel;
            if (page.collection.empty()) {
                rel = "layout.xml";
            }
            else if (ThemeProject::isSplashPage(page.collection)) {
                rel = "splash.xml";
            }
            else {
                if (!collectionFolderOk(page.collection)) {
                    plan.errors.push_back("collection template '" + page.collection + "' can't be a folder name");
                    continue;
                }
                rel = "collections/" + page.collection + "/layout/layout.xml";
            }
            GenResult r = generateLayoutXml(p, page, lib, opt);
            if (!r.ok()) {
                for (const auto& e : r.errors) plan.errors.push_back(label + ": " + e);
                continue;
            }
            for (const auto& w : r.warnings) plan.warnings.push_back(label + ": " + w);
            if (usesLetterArt(r.xml)) wantsLetters = true;
            addPage(rel, label, r.xml);
            if (!page.mons.empty()) {
                plan.warnings.push_back(label + ": second-screen pages aren't saved yet (this engine places "
                                        "components on a monitor with monitor= instead of layout1.xml)");
            }
            // A shared template is written into every member collection's folder
            for (const auto& m : page.members) {
                if (m.empty() || ThemeProject::isSplashPage(m)) continue;
                if (!collectionFolderOk(m)) {
                    plan.errors.push_back("template member '" + m + "' can't be a folder name");
                    continue;
                }
                plan.files.push_back({ "collections/" + m + "/layout/layout.xml", r.xml });
            }
        }
        if (plan.files.size() == 1 && plan.errors.empty()) plan.errors.push_back("nothing to save (no pages)");

        // RetroFE won't start on a layout without splash.xml: one with the theme's name
        if (inputs.splashFallback && !p.page(ThemeProject::splashPage()) && plan.errors.empty()) {
            const WidgetDef* text = lib.find("static_text");
            if (!text) {
                plan.warnings.push_back("the theme has no splash page, and RetroFE won't start on it without one");
            }
            else {
                ThemePage splash;
                splash.collection = ThemeProject::splashPage();
                WidgetInstance name;
                name.def = text->id;
                name.id = "theme_name";
                name.name = "Theme Name";
                name.w = p.canvasW() * 3 / 4;
                name.h = std::max(40, p.canvasH() / 12);
                name.x = (p.canvasW() - name.w) / 2;
                name.y = (p.canvasH() - name.h) / 2;
                name.layer = 1;
                name.setVar("VALUE", p.name);
                name.setVar("CENTER", "true");
                splash.widgets.push_back(name);
                GenResult r = generateLayoutXml(p, splash, lib, opt);
                if (r.ok()) {
                    addPage("splash.xml", "Splash", r.xml);
                }
                else {
                    plan.warnings.push_back("the theme has no splash page, and RetroFE won't start on it without one");
                }
            }
        }

        if (p.font.empty()) {
            if (inputs.fontBytes.empty()) {
                plan.warnings.push_back("the bundled font isn't available; the theme falls back to RetroFE's default font");
            }
            else {
                plan.files.push_back({ BUNDLED_FONT, inputs.fontBytes });
                plan.files.push_back({ BUNDLED_FONT_LICENSE, inputs.fontLicense.empty() ? bundledFontLicense() : inputs.fontLicense });
            }
        }

        if (wantsLetters) {
            const std::string& ttf = inputs.fontBytes;
            if (ttf.empty()) {
                plan.warnings.push_back("Game Letters is placed but there's no font to draw its tiles with");
            }
            else {
                std::vector<std::pair<std::string, std::string>> tiles;
                std::string error;
                if (!renderLetterTiles(ttf, LetterTileStyle(), tiles, error)) {
                    plan.errors.push_back("letter tiles: " + error);
                }
                else {
                    for (auto& t : tiles) plan.files.push_back({ std::string(LETTER_TILES_FOLDER) + "/" + t.first, std::move(t.second) });
                }
            }
        }
        return plan;
    }

    bool isPagePath(const std::string& rel)
    {
        if (rel == "layout.xml" || rel == "layout1.xml" || rel == "splash.xml") return true;
        const std::string prefix = "collections/";
        if (rel.compare(0, prefix.size(), prefix) != 0) return false;
        const size_t a = prefix.size();
        const size_t b = rel.find('/', a);
        if (b == std::string::npos || b == a) return false;
        const std::string collection = rel.substr(a, b - a);
        if (collection == "." || collection == "..") return false;
        const std::string tail = rel.substr(b);
        return tail == "/layout/layout.xml" || tail == "/layout/layout1.xml";
    }

    std::vector<std::string> stalePages(const std::vector<std::string>& planRelPaths,
                                        const std::vector<std::string>& existingEditorPages)
    {
        std::vector<std::string> out;
        for (const std::string& e : existingEditorPages) {
            if (e == "layout.xml" || !isPagePath(e)) continue;
            if (std::find(planRelPaths.begin(), planRelPaths.end(), e) != planRelPaths.end()) continue;
            if (std::find(out.begin(), out.end(), e) == out.end()) out.push_back(e);
        }
        return out;
    }
